import { Medication } from '@/lib/types/medication';

/**
 * Vademécum extendido (Sprint 5).
 * Formato compacto para mantener el archivo legible; `build()` lo expande al tipo `Medication`.
 *
 * Especies: C=Canino F=Felino E=Equino A=Ave X=Exótico O=Otro
 * Ingredientes: "Nombre:concentración:unidad|..."
 * Presentaciones: "Forma;concentración;vía|..."
 *
 * ⚠️ Información orientativa. El veterinario es responsable de verificar la dosis y la indicación.
 */

const SPECIES_MAP: Record<string, string> = {
  C: 'Canino',
  F: 'Felino',
  E: 'Equino',
  A: 'Ave',
  X: 'Exótico',
  O: 'Otro',
};

type Row = [
  id: string,
  names: string[],
  ingredients: string,
  therapeuticClass: string,
  action: string,
  species: string,
  indications: string[],
  contraindications: string[],
  presentations: string,
  flags?: { controlled?: boolean; keywords?: string[] },
];

const strip = (s: string) =>
  s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();

function build(row: Row): Medication {
  const [id, names, ingr, tClass, action, sp, ind, contra, pres, flags] = row;
  const activeIngredients = ingr.split('|').map((chunk) => {
    const [name, concentration = '', unit = ''] = chunk.split(':');
    return { name, concentration, unit };
  });
  const presentations = pres.split('|').map((chunk, i) => {
    const [form, concentration = '', route = 'Oral'] = chunk.split(';');
    return { id: `${id}-p${i + 1}`, form, concentration, route };
  });
  const keywords = new Set<string>([
    ...names.map(strip),
    ...activeIngredients.map((a) => strip(a.name)),
    strip(tClass),
    ...(flags?.keywords ?? []).map(strip),
  ]);
  return {
    id,
    commercialNames: names,
    activeIngredients,
    therapeuticClass: tClass,
    pharmacologicalAction: action,
    targetSpecies: sp.split('').map((c) => SPECIES_MAP[c]).filter(Boolean),
    indications: ind,
    contraindications: contra,
    searchKeywords: Array.from(keywords),
    presentations,
    isControlled: flags?.controlled ?? false,
    requiresPrescription: true,
    isGlobal: true,
    createdBy: 'system',
    version: 1,
  };
}

